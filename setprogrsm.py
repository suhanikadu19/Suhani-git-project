# Initialize set
fruits = {"apple", "banana", "cherry"}

# 1. Add a new element
fruits.add("orange")
print("After add('orange'):", fruits)

# 2. Remove an element using remove()
fruits.remove("banana")
print("After remove('banana'):", fruits)

# 3. Discard an element using discard()
fruits.discard("apple")
print("After discard('apple'):", fruits)